function normalizeArabic(text: string): string {
  return text
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[^\u0600-\u06FF0-9a-z\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Word-boundary safe Arabic token matcher (prevents false substring hits like "عمل" inside "اعمل").
 */
function hasWholeTerm(normQuery: string, queryTokens: string[], term: string): boolean {
  const normTerm = normalizeArabic(term);
  const termParts = normTerm.split(' ').filter(Boolean);
  if (termParts.length === 0) return false;

  if (termParts.length > 1) {
    const escaped = normTerm.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const regex = new RegExp(`(?:^|\\s)(?:و|ف|ب|ل|ك)?(?:ال)?${escaped}(?:$|\\s)`);
    return regex.test(normQuery);
  }

  const single = termParts[0];
  return queryTokens.some(
    (tok) =>
      tok === single ||
      tok === `ال${single}` ||
      tok === `و${single}` ||
      tok === `ب${single}` ||
      tok === `ل${single}` ||
      tok === `وال${single}` ||
      tok === `بال${single}` ||
      tok === `لل${single}`
  );
}

