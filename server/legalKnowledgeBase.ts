export function retrieveRelevantArticles(
  query: string,
  limit = 4
): { articles: LawArticle[]; matchedDomain: string; hotlines: HotlineEntry[] } {
  const normQuery = normalizeArabic(query);
  const queryTokens = normQuery.split(' ').filter((t) => t.length >= 2);

  // 1. Identify strict primary legal domain via whole-term domain classification
  const domainVotes = new Map<LegalDomainId, number>();
  for (const sig of DOMAIN_PRIORITY_SIGNALS) {
    let votes = 0;
    for (const pat of sig.patterns) {
      if (hasWholeTerm(normQuery, queryTokens, pat)) {
        votes += 10;
      }
    }
    if (votes > 0) {
      domainVotes.set(sig.domain, (domainVotes.get(sig.domain) ?? 0) + votes);
    }
  }

  // 2. Score articles using whole-term matching (NO blind substring matching)
  const scored = EGYPTIAN_LAW_ARTICLES.map((article) => {
    let score = domainVotes.get(article.domain) ?? 0;

    for (const kw of article.keywords) {
      if (hasWholeTerm(normQuery, queryTokens, kw)) {
        score += 15;
      }
    }

    const titleTokens = normalizeArabic(`${article.title} ${article.plainSummary}`)
      .split(' ')
      .filter((t) => t.length >= 3);
    for (const qt of queryTokens) {
      if (qt.length >= 3 && titleTokens.includes(qt)) {
        score += 3;
      }
    }

    return { article, score };
  });

  scored.sort((a, b) => b.score - a.score);

  const topArticle = scored[0];
  let primaryDomain: LegalDomainId = 'civil';
  if (topArticle && topArticle.score > 0) {
    primaryDomain = topArticle.article.domain;
  } else if (domainVotes.size > 0) {
    primaryDomain = [...domainVotes.entries()].sort((a, b) => b[1] - a[1])[0][0];
  }

  // 3. STRICT LEGAL DOMAIN ISOLATION: never mix labor into penal/harassment/family/cyber
  const allowedDomains = new Set<LegalDomainId>([primaryDomain]);
  if (primaryDomain === 'penal') {
    allowedDomains.add('criminal_proc');
  } else if (primaryDomain === 'cyber') {
    if (hasWholeTerm(normQuery, queryTokens, 'نصب') || hasWholeTerm(normQuery, queryTokens, 'تهديد') || hasWholeTerm(normQuery, queryTokens, 'فلوس')) {
      allowedDomains.add('penal');
    }
    allowedDomains.add('criminal_proc');
  }

  const strictlyFiltered = scored
    .filter((s) => allowedDomains.has(s.article.domain) && (s.score > 0 || s.article.domain === primaryDomain))
    .slice(0, limit)
    .map((s) => s.article);

  const selected =
    strictlyFiltered.length > 0
      ? strictlyFiltered
      : EGYPTIAN_LAW_ARTICLES.filter((a) => a.domain === primaryDomain).slice(0, limit);

  const matchedDomain = selected[0]?.domainNameAr ?? 'استشارة قانونية عامة';

  const domainToHotlineCat: Record<LegalDomainId, HotlineEntry['category'][]> = {
    labor: ['labor', 'complaints'],
    cyber: ['cyber', 'emergency'],
    family: ['family', 'emergency'],
    consumer: ['consumer', 'complaints'],
    penal: hasWholeTerm(normQuery, queryTokens, 'تحرش') || hasWholeTerm(normQuery, queryTokens, 'معاكسة')
      ? ['emergency', 'family']
      : ['emergency', 'complaints'],
    criminal_proc: ['emergency', 'complaints'],
    civil: ['complaints'],
    rent: ['complaints'],
  };

  const targetCats = domainToHotlineCat[primaryDomain] ?? ['emergency', 'complaints'];
  const hotlines = EGYPTIAN_HOTLINES.filter((h) => targetCats.includes(h.category)).slice(0, 3);

  return { articles: selected, matchedDomain, hotlines };
}
