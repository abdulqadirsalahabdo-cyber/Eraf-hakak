function normalizeArabic(text: string): string {
  return text
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '') // remove tashkeel
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[^\u0600-\u06FF0-9a-z\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function retrieveRelevantArticles(
  query: string,
  limit = 4
): { articles: LawArticle[]; matchedDomain: string; hotlines: HotlineEntry[] } {
  const normQuery = normalizeArabic(query);
  const tokens = normQuery.split(' ').filter((t) => t.length >= 2);

  const scored = EGYPTIAN_LAW_ARTICLES.map((article) => {
    let score = 0;
    const searchable = normalizeArabic(
      `${article.title} ${article.domainNameAr} ${article.plainSummary} ${article.officialText} ${article.keywords.join(' ')}`
    );

    for (const kw of article.keywords) {
      const normKw = normalizeArabic(kw);
      if (normQuery.includes(normKw)) {
        score += 12;
      } else {
        const kwParts = normKw.split(' ');
        for (const p of kwParts) {
          if (p.length >= 3 && normQuery.includes(p)) score += 4;
        }
      }
    }

    for (const token of tokens) {
      if (searchable.includes(token)) {
        score += 2;
      }
    }

    return { article, score };
  });

  scored.sort((a, b) => b.score - a.score);
  const top = scored.filter((s) => s.score > 0).slice(0, limit).map((s) => s.article);

  const selected = top.length > 0 ? top : [EGYPTIAN_LAW_ARTICLES[0], EGYPTIAN_LAW_ARTICLES[6], EGYPTIAN_LAW_ARTICLES[12]];
  const primaryDomain: LegalDomainId = selected[0]?.domain ?? 'civil';
  const matchedDomain = selected[0]?.domainNameAr ?? 'استشارة قانونية عامة';

  const domainToHotlineCat: Record<LegalDomainId, HotlineEntry['category'][]> = {
    labor: ['labor', 'complaints'],
    cyber: ['cyber', 'emergency'],
    family: ['family', 'emergency'],
    consumer: ['consumer', 'complaints'],
    penal: ['emergency', 'cyber', 'complaints'],
    criminal_proc: ['emergency', 'complaints'],
    civil: ['complaints', 'emergency'],
    rent: ['complaints']
  };

  const targetCats = domainToHotlineCat[primaryDomain] ?? ['emergency', 'complaints'];
  const hotlines = EGYPTIAN_HOTLINES.filter((h) => targetCats.includes(h.category)).slice(0, 3);

  return { articles: selected, matchedDomain, hotlines };
}
